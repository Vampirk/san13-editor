const char* SettlementNameTable::GetSettlementName(uint16_t id) {
    auto it = KNOWN_SETTLEMENT_NAMES.find(id);
    if (it != KNOWN_SETTLEMENT_NAMES.end()) {
        return it->second;
    }
    return nullptr;
}

std::string SettlementNameTable::GetFormattedName(uint16_t id, const std::string& cityName) {
    const char* known = GetSettlementName(id);
    char buf[64];
    if (known) {
        return std::string(known);
    }
    
    if (!cityName.empty()) {
        std::snprintf(buf, sizeof(buf), "[%s] 부락 #%03u", cityName.c_str(), id);
    } else {
        std::snprintf(buf, sizeof(buf), "부락 #%03u", id);
    }
    return std::string(buf);
}

const char* SettlementNameTable::GetEffectName(uint8_t effectId) {
    auto it = KNOWN_EFFECT_NAMES.find(effectId);
    if (it != KNOWN_EFFECT_NAMES.end()) {
        return it->second;
    }
    return nullptr;
}

std::string SettlementNameTable::GetEffectDescription(const uint8_t buff_effects[4]) {
    std::string desc;
    for (int i = 0; i < 4; ++i) {
        uint8_t eff = buff_effects[i];
        if (eff == 255) continue;
        const char* name = GetEffectName(eff);
        if (name) {
            if (!desc.empty()) desc += ", ";
            desc += name;
        }
    }
    return desc.empty() ? "-" : desc;
}

